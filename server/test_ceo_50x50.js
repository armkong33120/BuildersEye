const delay = (ms) => new Promise(resolve => setTimeout(resolve, ms));

async function run() {
  console.log('Starting CEO Stress Test (50x50)...');
  const fd = fs.openSync('ceo_test_results.csv', 'w');
  fs.writeSync(fd, 'TargetID,Question,SqlUsed,AnswerSource,Answer\n');
  
  let count = 0;
  // วนลูปรายชื่อพนักงาน 50 คน (EMP001 ถึง EMP050)
  for (let targetId = 1; targetId <= 50; targetId++) {
    const targetEmp = `EMP${String(targetId).padStart(3, '0')}`;
    
    // วนลูป 50 คำถามของ CEO
    for (let qIdx = 0; qIdx < ceoQuestions.length; qIdx++) {
      const template = ceoQuestions[qIdx];
      const query = template.replace(/{name}/g, targetEmp);
      
      try {
        const res = await fetch('http://localhost:5199/api/chat', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ 
            query: query, 
            viewer: { role: 'CEO', employeeId: 1 }, 
            conversationId: `ceo-test-${targetId}` 
          })
        });

        const data = await res.json();
        const cleanAnswer = data.answer ? data.answer.replace(/\n/g, ' ').replace(/"/g, '""') : '';
        const sqlUsed = data.sqlUsed ? 'TRUE' : 'FALSE';
        const source = data.answerSource || 'unknown';
        
        fs.writeSync(fd, `"${targetEmp}","${query}","${sqlUsed}","${source}","${cleanAnswer}"\n`);
        count++;
        
        console.log(`[${count}/2500] ${targetEmp} | Q${qIdx+1} -> OK (${source})`);
        await delay(1000); // หลบ Rate Limit 1 วินาที

      } catch (err) {
        console.error(`[${count}/2500] ${targetEmp} | Q${qIdx+1} -> ERROR: ${err.message}`);
        fs.writeSync(fd, `"${targetEmp}","${query}","ERROR","ERROR","${err.message}"\n`);
        await delay(3000);
      }
    }
  }
  
  fs.closeSync(fd);
  console.log('Finished CEO Stress Test! Saved to ceo_test_results.csv');
}

run();
